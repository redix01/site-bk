<div class=" instructions l-stack l-stack--goat">
    
    
        
        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <p>Article 39 FMIA obligates the participants of trading venues in Switzerland to report certain information in order to identify the beneficial owner for securities transactions (purchases and sales). This affects securities admitted on a trading venue in Switzerland and derivatives based on such securities.</p>
<p>What information does the bank report?</p>
<ul>
<li><p>In the case of natural persons, this information includes an identity number internal to the bank, nationality and the date of birth of the beneficial owner.</p>
</li>
<li><p>In the case of legal entities, the LEI (Legal Entity Identifier), the business identifier code or the commercial register number are reported.</p>
</li>
</ul>
<p>Who does the bank report your customer information to?</p>
<ul>
<li>The information is reported to a reporting office set up by the trading venues (such as the SIX Swiss Exchange).</li>
</ul>
<p>Last updated: February 2018</p>

