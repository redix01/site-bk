        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <p>MiFIR affects securities transactions (purchases and sales) which are processed by Zürcher Kantonalbank for its customers directly via a relevant trading venue. The large majority of transactions to foreign trading venues are sent by Zürcher Kantonalbank to trading venues abroad via a broker; in such cases, no information about the customer has to be reported. Zürcher Kantonalbank processes transactions to the following trading venues as a direct participant, i.e. without the use of a broker.</p>
<p>Currently, a duty to report applies to the following transactions:</p>
<ul>
<li>Standardised EUREX derivatives</li>
<li>Eurobonds traded on Bloomberg MTF, MarketAxess Europe Limited MTF or Tradeweb Europe Limited MTF</li>
<li>Exchange-traded funds traded at the NAV (instead of the exchange rate) on Tradeweb Europe Limited MTF<br>
</li>
</ul>
<p>This affects both orders issued directly by the customer as well as orders executed as part of an asset management mandate.</p>
<p>Last updated: January 2018&nbsp;</p>

