    <h3>Execution of orders / forwarding to the relevant trading venues</h3>
<ul>
<li>During service hours from 8 a.m. to 6 p.m., orders are forwarded to the relevant trading venues.</li>
<li>Furthermore, Orders for trading venues in North America are forwarded to the relevant trading venues until 10 p.m.</li>
<li>Orders for subscription or redemption of fund units are subject to deadlines of the order routing platform.</li>
</ul>
<div>The provisions in bilateral agreements on securities trading and trading practices between financial institutions or with professional clients may deviate from the above.</div>
<div>&nbsp;</div>
<div>Please also note the opening hours of the respective trading venues and trading systems.</div>
