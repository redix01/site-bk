    <p>Zürcher Kantonalbank offers a broad range of financial services and products in the areas of trading and capital market business as well as research, and serves a broad and diverse client and investor base in different capacities. In addition, Zürcher Kantonalbank may also trade on its own account in these business areas. Consequently, potential conflicts of clients’ and investor’s interests, or conflicts between Zürcher Kantonalbank's and clients’ or investor’s interests, are to a certain extent unavoidable. Zürcher Kantonalbank has policies and procedures in place to identify and prevent or manage conflicts (or perceived conflicts) of interest. This document summarises these policies and procedures issued specifically for the trading and capital market business as well as research.</p>
