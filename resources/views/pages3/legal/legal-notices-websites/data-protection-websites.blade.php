    <h3>Personal Data</h3>
<p>If you provide us with your personal data (such as your name, gender, address, e-mail, telephone or fax number) via the ZKB website using a form or another method, our Bank may use this data for the following purposes in accordance with section 2.4:<br>
</p>
<ul>
<li>Client and user administration</li>
<li>Internal marketing purposes and to keep you informed about our products and services</li>
<li>Technical management and development of the ZKB website</li>
</ul>

