    <h3>General Terms</h3>
<p>This information supplements our data protection declaration with respect to our Bank's website (zkb.ch and its sub-sites; "ZKB website").<br>
</p>
<p>When you visit the ZKB website our web server automatically records certain details of your visit (e.g. your IP address, the website you are visiting us from and the ZKB website you are visiting, including the date and duration of your visit). Tracking data is used to optimise the offering on the ZKB website and provide information on how you find out about our products and services and how you use them. However, it does not allow you to be identified; no personal data is processed in this respect.</p>

</div>


    

</div>
