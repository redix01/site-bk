    <h3>Security of data transmission</h3>
<p>When you visit the ZKB website your data is transmitted over the internet, an open network that is accessible to everyone. Data that you transmit to our Bank via electronic media (such as e-mail) or have transmitted to you by our Bank is generally not encrypted. This involves the following specific risks:<br>
</p>
<ul>
<li>Even if the sender and recipient are in Switzerland, data may be transmitted abroad on an uncontrolled basis via countries whose data protection laws are not comparable to those of Switzerland.</li>
<li>The identity of the sender (e.g. e-mail address) and the content of the message may be simulated or otherwise manipulated by unauthorised persons.<br>
Electronic messages may contain malware that is executed when the message is read and may cause substantial damage. To prevent viruses we recommend using the latest versions of browsers and installing continually updated anti-virus software.</li>
<li>The exchange of information may be delayed or interrupted by transmission errors, technical faults, interruptions, malfunctions, illegal interference, network overload, malicious blocking of the network by third parties, or other deficiencies.<br>
</li>
</ul>
