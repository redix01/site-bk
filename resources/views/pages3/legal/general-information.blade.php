<h3>Deposit Insurance</h3>
<p>Deposit insurance protects the credit balances of private and corporate clients in the event of a bank or securities firm’s bankruptcy. This guarantee is regulated by law. The protection is limited to a maximum of CHF 100'000.– per client and institution. Multiple accounts are added together. «esisuisse» guarantees that it will cover protected deposits as part of the self-regulation of Swiss banks and securities firms. Deposits at Zürcher Kantonalbank are covered by the deposit insurance scheme. Detailed information at <a href="http://www.esisuisse.ch/" target="_blank" rel="noreferrer">esisuisse.ch</a></p>
<p>In addition, the Canton of Zurich is liable under the state guarantee for all liabilities (excluding subordinated liabilities) of Zürcher Kantonalbank if the bank's own funds are insufficient.</p>
