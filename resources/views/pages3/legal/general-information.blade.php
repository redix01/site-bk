    <h3>Field of Activity and Supervisory Status</h3>
<p>As an independent public law institution (selbständige öffentlich-rechtliche Anstalt) established pursuant to the laws of the Canton of Zurich and of Switzerland, Zürcher Kantonalbank conducts the typical business activities of a large universal bank. Its core business includes account management, payment services and card business, financing business, investment and asset management business, as well as securities trading and the capital market business. Moreover, it offers additional services such as leasing business as well as advisory services in financial, tax, inheritance, succession and real estate matters. To serve and advise its clients in the best possible way, Zürcher Kantonalbank uses, if appropriate and necessary, the services of its subsidiaries inside and outside Switzerland, such as fund management companies in Zurich and Luxembourg.</p>
<p>Zürcher Kantonalbank holds an authorisation of the Swiss Financial market Supervisory Authority (FINMA) pursuant to the Federal Law on Banks and Savings Banks (Banking Act) to operate as a bank in Switzerland. Its business operations are subject to continuous supervision by FINMA.</p>
