    <h3>Ombudsman proceedings</h3>
<p>Client satisfaction is important to Zürcher Kantonalbank. Clients who are not entirely satisfied with the services of Zürcher Kantonalbank are advised to contact their relationship manager. Whenever possible, Zürcher Kantonalbank aims to find an amicable solution with the client.</p>
<p>Should this effort not be successful in a specific case, the client can contact the Swiss Banking Ombudsman, which is a neutral information and mediation institution that Zürcher Kantonalbank has affiliated with. As a rule, the Swiss Banking Ombudsman becomes active only after a client has submitted a complaint in writing to the bank and has given the latter the opportunity to comment or settle the matter directly.</p>
<p>The contact details of the Swiss Banking Ombudsman are the following:</p>
