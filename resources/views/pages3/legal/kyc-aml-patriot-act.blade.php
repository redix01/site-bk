    <p>Please read the following important legal notices regarding supervision, money launderiing and the Patriot Act.</p>
<h3>Know Your Customer (KYC)</h3>
<p>Zürcher Kantonalbank has its headquarters in Zurich, Switzerland, and is supervised by the Swiss Financial Market Supervisory Authority (FINMA). The confirmation that Zürcher Kantonalbank is licensed to conduct banking activities can be found on the FINMA website.</p>
<p>The latest annual report of Zürcher Kantonalbank, the list of current Board members and further information is available on our website.</p>
<h3>Anti Money Laundering (AML)</h3>
<p>Zürcher Kantonalbank is subject to provisions on Anti Money Laundering (AML) under Swiss Law, which are in accordance with the FATF recommendations (Switzerland is a member country of the Financial Action Task Force FATF). This means in particular that Zürcher Kantonalbank has to identify its clients and establish the beneficial owner's identity. The AML compliance policies approved by the Management Board include inter alia the processes for the identification of customers and establishing the identity of the beneficial owner. The policies also cover the collection of information regarding customers' business activities, relationships with Politically Exposed Persons and record retention procedures. Furthermore, Zürcher Kantonalbank regularly provides AML training to relevant employees and does not provide banking services to any bank that does not maintain a physical presence in any country and that is not a regulated affiliate. The anti-money laundering policies are applicable to head office and branches alike and are in accordance with the Wolfsberg anti-money laundering principles.</p>
<h3>Patriot Act</h3>
<p>Zürcher Kantonalbank has prepared a global Patriot Act Certification for use by any financial institution that believes it requires a Patriot Act Certification from Zürcher Kantonalbank. Please use this certification instead of asking Zürcher Kantonalbank to complete a separate certification form.</p>
<h3>Transaction Monitoring</h3>
<p>Zürcher Kantonalbank has an automated monitoring programme for unusual and potentially suspicious activity. Due to the statutory provisions of Swiss Law, a report to the Authorities must be submitted, if the assets involved in the business are connected with a criminal organisation or money laundering, originates from a crime or serve the financing of terrorism.</p>
<h3>Sanction Screening</h3>
<p>Zürcher Kantonalbank has procedures to regularly screen its clients (natural persons and legal entities) and their transactions against sanctions lists.</p>
