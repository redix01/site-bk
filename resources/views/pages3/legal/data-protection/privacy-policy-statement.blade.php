    <p>Depending on which products and services the Bank provides for you, it can process the following categories of personal data. The Bank’s policy is to process as little personal data as necessary.</p>
<h4>2.1.1&nbsp;Former, current and potential customers (or prospective customers)</h4>
<p>These include, in particular, the following:</p>
<ul>
<li>Master and inventory data such as name, address, telephone number, e-mail address, date of birth, nationality, profession, economic and family circumstances, financial goals, investment knowledge and experience, contract number and duration, identification and authentication data, e.g. login for eBanking, documents to establish the customer's identity, such as an identity document or passport, information about the account, securities account, cards and payments, about current or completed transactions, contracts, products, services; information about third parties, such as life companions, family members, authorised representatives and advisors who are also affected by a data processing.</li>
<li>Fiscal domicile and any other documents and information which may be relevant in terms of tax.</li>
<li>Transaction or order and risk management data, for example, information on the beneficiary, counterparty or third-party banks in the case of transfers or card payments and, where applicable, details of issued mandates, information concerning your assets, real estate, lines of credit, credit rating, investment products, risk and investment profile, cases of fraud, enquiries, consultations, conversations and physical or electronic correspondence.</li>
<li>Personal data requiring special protection (sensitive personal data), such as biometric data for voice recognition during telephone calls for the identification of the caller.</li>
<li>Recordings of telephone calls between you and the Bank, if applicable, or video recordings of your visit to our premises or your use of our ATMs.</li>
<li>Marketing data, such as the needs, wishes, interests, preferences, information about the use of products, services or contact and communication channels.</li>
<li>Technical data such as internal and external identifiers, trade numbers, IP addresses, location in apps (for example ZKB TWINT), records of accesses or changes.</li>
</ul>
<h4>2.1.2&nbsp;Visitor information (i.e. visitors of branches or websites)</h4>
<p>These include, in particular, the following:</p>
<ul>
<li>Master data and inventory data, such as name, telephone number, e-mail address, address, date of birth and personal data collected using a form.</li>
<li>Recordings of telephone calls between you and the Bank, if applicable, or video recordings of your visit to our premises or your use of our ATMs.</li>
<li>Technical data, such as internal or external identifiers, IP addresses, and logs of access or changes.</li>
<li>Marketing data, for example, needs, wishes, preferences and interactions.</li>
<li>Data that is transmitted to us on account of your visit to our websites or that you provide to us (e.g. using a form).</li>
</ul>
<h4>2.1.3&nbsp;Supplier Employee Data</h4>
<p>These include, in particular, the following:</p>
<ul>
<li>Master data and inventory data such as name, address, position, telephone number, e-mail address, date of birth, contract number and duration, and information on current or concluded services, products or projects.</li>
<li>Recordings of telephone calls between you and the Bank, if applicable, or video recordings of your visit to our premises or your use of our ATMs.</li>
<li>Technical data, for example internal and external identifiers, trade numbers, IP addresses, records of accesses or changes.</li>
</ul>
