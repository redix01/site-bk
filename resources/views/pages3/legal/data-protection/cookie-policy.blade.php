    <h2>Scope of the Cookie and Tracking Policy</h2>
<p>This Cookie and Tracking Policy applies to the Bank's digital offerings, which refer to it. In particular, it applies to:&nbsp;</p>
<ul>
<li>the Bank's main website on zkb.ch and sub-pages (hereinafter referred to as the "ZKB website")&nbsp;</li>
<li>the Bank's eBanking after logging in to onba.zkb.ch (hereinafter referred to as "eBanking") and</li>
<li>mobile applications from the Google/Android and Apple app stores: ZKB Mobile Banking, ZKB Info app, ZKB Access app and ZKB Twint (hereinafter collectively referred to as "mobile apps")</li>
</ul>
<p>There may be additional or different provisions for the use of tracking data for certain digital offerings of the Bank, e.g. social media channels, other mobile apps or separate websites. These are available on the corresponding digital platforms and take precedence in these cases. The Bank has no influence on digital sites that comment on or about Zürcher Kantonalbank, but are not operated by the Bank or on its behalf. This Cookie and Tracking Policy does not apply in this case.&nbsp;</p>
<h3>Which tracking technology do we use?</h3>
<p>In connection with our digital platforms, we use cookies, software development kits (hereinafter referred to as "SDKs") and other measurement technologies (hereinafter referred to as "tracking technologies").&nbsp;</p>
<p>Some of our tracking technologies are necessary for the provision and proper functioning of our digital platforms. Their use cannot be waived (hereinafter referred to as "necessary tracking technologies"). Other tracking technologies are used for statistical evaluation and to improve your user experience, e.g. through personalised offers or by displaying advertising on external websites. You can adapt the settings for the use of tracking technologies to suit your preferences at any time (detailed information on the options can be found in the sections "Options on the ZKB website" and "Options in eBanking"). The use of tracking technologies in the mobile apps is approved by downloading the respective mobile app. Such use is rejected by refraining from downloading the apps.</p>
<h3>What are tracking technologies and how do they work?</h3>
<p>We use various tracking technologies on our digital platforms, in particular cookies and SDKs. A list of the cookies and SDKs used can be found in the "Which third-party cookies and tracking SDKs do we use?" section.</p>
<h3>Cookies</h3>
<p>Cookies are small text files which are stored in your browser. This allows the digital offering (e.g. the ZKB website) to remember certain inputs and settings (e.g. login, language, usage, preferences and statistics) over a certain period of time.</p>
<p>Cookies can be set as first-party cookies by saving them on the domain of the respective website (e.g. ZKB website). These first-party cookies can only be read by the operators of the respective website (in this case the Bank). These first-party cookies are set by means of the operator's technical integrations (i.e. by the Bank) or by the integration of third-party products (e.g. Adobe Analytics).</p>
<p>Cookies can also be set as third-party cookies. This happens when the cookies can also be read directly by other websites and website operators. The Bank uses third-party cookies very sparingly and only in publicly accessible areas.</p>
<h3>How long are cookies stored in your browser?</h3>
<p>Some cookies are automatically deleted as soon as the browser session has ended or after a specified period of time. Certain cookies are permanently stored in the browser for technical reasons, unless deleted by the user or reset by the user during a subsequent visit to the digital platforms.&nbsp;</p>
<h3>SDKs</h3>
<p>SDKs are code packages which are integrated into the source code of a mobile app and are automatically installed when the app is downloaded. This allows the app to remember various inputs and settings for the entire duration of the installation and link them to the user behaviour.&nbsp;</p>
<h3>How long are SDKs stored in mobile apps?</h3>
<p>The SDKs used in mobile apps are initiated and permanently installed when the app is downloaded to the mobile device. They remain in the app until the mobile app is deleted or uninstalled from the device.&nbsp;</p>
<h3>What data is stored and processed?</h3>
<p>The tracking technologies used with your consent read tracking data (e.g. the webpage or URL you are currently visiting, including the date and duration of your visit as well as technical data on your device such as browser, operating system and IP address). This tracking data is required for statistical purposes for the optimisation and further development of the digital platform and for the display of offers and content tailored to your interests.&nbsp;</p>
<p>If you decline the use of tracking technologies, we will only use necessary tracking technologies on the ZKB website and in eBanking to enable the proper functioning of our digital offerings.</p>
<p>Tracking data generally does not contain any directly personally identifiable characteristics. However, the Bank may merge tracking data with other data already held by the Bank and thus possibly establish links to personal identities. <a href="../legal-notices-websites/data-protection-websites.html">Zürcher Kantonalbank's privacy policy</a> provides information on how the Bank handles personal data.</p>
<p>If third-party products are used for tracking on ZKB's digital channels, the Bank will only forward pseudonymised data to these third-party providers. This data in itself does not allow the third-party providers to identify a specific person.</p>
<h3>Which third-party cookies and SDKs do we use?</h3>
<p>Besides cookies from our own systems, we use cookies and SDKs from service providers and third-party products. An overview of these products can be found below.</p>

