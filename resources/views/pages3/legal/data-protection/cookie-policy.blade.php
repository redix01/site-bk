    <p>When you visit our digital offerings, the details of your visit (e.g. your IP address, the website from which you visit us or the ZKB website you are currently visiting, including the date and duration of your visit, hereinafter referred to as "tracking data") are automatically registered. Such tracking data is stored on your device or read from it. Tracking data is used to optimise the content offered on our communication channels, in particular our websites, eBanking and mobile applications, and provide information on how you find out about our products and services and navigate our digital channels.</p>
<p>This Cookie and Tracking Policy describes how Zürcher Kantonalbank (hereinafter referred to as the "Bank") collects such tracking data and how it handles this data. This Policy may be updated at any time. Please check this page regularly for the latest version.&nbsp;</p>

