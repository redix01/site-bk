<div class=" instructions l-stack l-stack--goat">
    
    
        
        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <p>The Zürcher Kantonalbank media office can add media representatives, subscribers to ad-hoc notifications and other interested parties to its database for media work and mailings. In accordance with the applicable data protection law and in addition to the privacy policy statement, the following additional information are relevant to them.</p>
<p>The database includes media representatives, subscribers to ad-hoc notifications and other contacts that enable the creation of contact lists for the purpose of:</p>
<ul>
<li>sending media releases and ad hoc information,</li>
<li>sending invitations as part of media events,</li>
<li>contacting journalists if the bank has information for the medium in question.</li>
</ul>
<p>Information about you that is intended for the Corporate Communications media office (first name, last name, e-mail addresses and, if necessary, telephone numbers, job titles, topics or social media profiles of media representatives) will be retained for as long as it is required for the above-mentioned purposes, unless you exercise your right to delete the data concerning you.</p>
<p>The data in the media database and for the distribution of media notifications are processed in Switzerland, Germany and France (server location).</p>
<p>For media enquiries and in the context of general media work, personal data of media representatives (name, medium, contact address, questions and answers) can also be recorded in a planning tool, i.e. for planning and processing reactive and active media work as well as for the purpose of traceability of enquiries made in advance. Personal data of other contacts (e.g. interview partners) can also be recorded in the planning tool for the purpose of planning and drafting the statements of Corporate Communications that appear on external or internal channels of the Zürcher Kantonalbank. In addition to Switzerland, the data in the planning tool can also be processed on servers in the following countries: Germany, Republic of Ireland, Luxembourg, Poland or Spain. Personal data of other contacts (e.g. interview partners) can also be accessed as part of the content and articles on an employee app, whose data is processed in Switzerland, Germany and Finland (server locations).</p>

