    <h1 class="t-title t-title--page">Money Transfers &amp; Securities Transactions</h1>
    <p class="t-lead">Important legal notices on data privacy in money transfers and securities transactions.</p>
</div>

    

</div>
<div class="dt-container">






<div class=" instructions l-stack l-stack--goat">
    
    
        
        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <p>Financial institutions exchange information and messages when conducting money transfers and securities transactions. This exchange occurs when conducting all kinds of domestic and foreign transactions (bank transfers, direct debits, securities transactions, etc.) regardless of the currencies used. This is essential in order to ensure the necessary connection between all financial institutions and to process transactions correctly for customers.</p>
<p>By providing your personal data (name, address and IBAN/account or safe custody account number) you thereby declare that you consent to this data being disclosed to the parties below when conducting domestic and foreign transactions:</p>
<ul>
<li>Domestic and foreign financial institutions (correspondent banks and financial institutions of the beneficiaries).</li>
<li>System operators such as SIX Interbank Clearing AG or the Society for Worldwide Interbank Financial Telecommunication (SWIFT).</li>
<li>Beneficiaries in Switzerland and abroad.</li>
</ul>
<p>Customer data may go abroad - and no longer be subject to Swiss law – when conducting domestic transactions, not just foreign ones. Foreign authorities may have access to the data depending on the legal provisions applicable at the place where it is stored.</p>
<p>The Swiss Bankers Association, in consultation with the Swiss Financial Market Supervisory Authority (FINMA) and the Swiss Federal Data Protection and Information Commissioner (FDPIC), has drafted general information in the form of questions and answers on the disclosure of customer data when conducting money transfers, securities and other transactions in connection with SWIFT (SwissBanking information).</p>
<p>More information:</p>
<ul>
<li><a href="https://www.swissbanking.org/de/themen/informationen-fuer-privatkunden/20160219-3200-all-informationsschreiben_webversion_d-cla.pdf" target="_blank" rel="noreferrer">Download document from SwissBanking Website&nbsp;in German</a></li>
<li><a href="https://www.finma.ch/en/news/2009/06/aktuell-finma-mitteilung2-20090617/" target="_blank" rel="noreferrer">Visit the FINMA website</a></li>
</ul>
