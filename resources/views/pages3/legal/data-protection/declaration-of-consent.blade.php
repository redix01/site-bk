    <p>Please read the following legal notices regarding the disclosure of customer data for financial market and foreign exchange transactions.</p>
<p>Zürcher Kantonalbank trades and holds in custody securities and financial instruments with a foreign element and/or executes fiduciary investments and foreign exchange transactions on behalf of the customer. In this regard, owing to foreign law and contractual provisions, it may be necessary for the Zürcher Kantonalbank to disclose for whom it is acting. The customer's consent is required in order that Zürcher Kantonalbank can disclose data where necessary.</p>
<p>At present Zürcher Kantonalbank requires a Declaration of Consent in relation to the following services:</p>
<ul>
<li>The trading and safekeeping of securities and financial instruments with a foreign element&nbsp;&nbsp;</li>
<li>Investment advice (with a contract)&nbsp;</li>
<li>Discretionary Mandates</li>
</ul>
<p>For further information please refer to the declaration of consent, the information sheet of Zürcher Kantonalbank or the information sheet of the Swiss Bankers Association.</p>
