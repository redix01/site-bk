<div class="zkb-component zkb-component--structure-title"><div class="l-max-width l-max-width--coconut">
    <h1 class="t-title t-title--page">Whistleblowing</h1>
    <p class="t-lead">Secure system for reporting alleged malpractices, even anonymously, if necessary.</p>
</div>

    

</div>
<div class="dt-container">






<div class=" instructions l-stack l-stack--goat">
    
    
        
        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>General</h3>
<p>The integrity and reputation of Zürcher Kantonalbank are among the most important assets of the company. For this reason, Zürcher Kantonalbank and its subsidiaries rely on their employees and third parties (e.g. customers, suppliers, competitors) to learn of alleged malpractices within the organisation. Employees who submit a report in good faith do not have to fear any disadvantageous consequences.</p>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Reporting platform</h3>
<p>Zürcher Kantonalbank has established a highly secure reporting platform (BKMS® reporting system) for the reporting of alleged malpractices within the organisation, even anonymously, if desired. Examples of malpractice include violations of criminal, regulatory or administrative laws as well as other legal regulations and internal rules. Please direct customer complaints as usual to our contact offices:&nbsp;<a href="../home/contact.html" target="_blank" rel="noreferrer">Contact us</a></p>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Independent report-processing office</h3>
<p>Reports can either by entered via the BKMS® reporting system or sent in letter form to the independent report-processing office.</p>
<ul>
<li>Via the BKMS® reporting system:&nbsp;<a href="https://www.bkms-system.ch/bkwebanon/report/clientInfo?cin=ghjp3k&amp;c=-1&amp;language=eng" target="_blank" rel="noreferrer">Report malpractice</a></li>
<li>By mail: Streiff von Kaenel AG, Attorneys, Bahnhofstrasse 67, Postfach, 8620 Wetzikon</li>
</ul>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Further process</h3>
<p>Relevant violations are forwarded by the attorney’s office Streiff von Kaenel AG to a trusted employee of Zürcher Kantonalbank and then investigated by the competent office in accordance with the internal rules and regulations. Consideration is given to potential conflicts of interest.</p>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Confidentiality</h3>
<p>All information and investigations are handled confidentially. The employees of the report-processing office are subject to business and banking secrecy.</p>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Thank you very much</h3>
<p>Your reports will help us avert financial damage, protect our reputation and ensure the long-term success of the organisation. Thank you for your valuable support.</p>
<p>&nbsp;</p>
<p>Last update: February 2019</p>

