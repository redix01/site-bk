    <p>Zürcher Kantonalbank always aims to organise its business activities in such a way that the interests of clients, the bank and its employees are aligned as much as possible. Nonetheless, conflicts of interest cannot always be avoided. Zürcher Kantonalbank aims to deal with such potential conflicts of interest transparently and fairly by abiding by the rules set out in the Code of Conduct of Zürcher Kantonalbank.</p>
<p>Please see the information below on selected measures for dealing with conflicts of interest.</p>
