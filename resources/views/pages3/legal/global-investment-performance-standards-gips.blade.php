    <h2>Meaning and purpose of GIPS Standards</h2>
<p>GIPS Standards are international standards and recommendations used by asset managers outlining how key figures for performance and risk may be presented to customers. Mandates with similar strategic orientations are combined into so-called «composites» and their performance is presented on a consolidated basis. The GIPS Standards provide the following advantages:</p>
<ul>
<li>Consistency and verifiability in the calculation and presentation of the performance results realised as well as aggregation of the individual composites.</li>
<li>Comparability of the performance results of composites and/or pooled funds with other institutes, irrespective of the strategic orientation, for existing and potential investors.</li>
<li>Transparency due to the publication of quantitative key figures and explanatory information in the GIPS reports.</li>
<li>Full disclosure of the relevant mandates and the corresponding period results in avoiding «cherry picking».<br>
</li>
</ul>
<h2>GIPS compliance and the firm<br>
</h2>
<h3>For institutional asset management mandates:</h3>
<p>The GIPS firm «Vermögensverwaltungsmandate des Asset Managements der Zürcher Kantonalbank» claims compliance with the Global Investment Performance Standards (GIPS®) and comprises all asset management mandates managed&nbsp;in the head office in Zurich by Zürcher Kantonalbank's institutional asset management. All Swisscanto fund solutions and private asset management mandates are not included. In terms of the GIPS Standards, all mandates that have a certain minimum portfolio size and are independent of their customers in terms of their investment decisions are regarded as discretionary.</p>
<p>The GIPS&nbsp;firm «Vermögensverwaltungsmandate des Asset Managements der Zürcher Kantonalbank» has been independently verified for the period from 1 January 1993 to 31 December 2022 by PricewaterhouseCoopers AG. Verification is carried out annually and the most recent verification report was prepared as of 31 December 2022.</p>
<h3>For funds:</h3>
<p>The GIPS firm «Swisscanto Fonds &amp; ETF» claims compliance with the Global Investment Performance Standards (GIPS®) and &nbsp;is defined as the investment management business of investment funds including exchange-traded funds and investment groups of Zürcher Kantonalbank, Zurich. The Firm does not include segregated asset management portfolios of private, professional and institutional clients, which are part of the GIPS firms «ZKB Standardmandate» and «Vermögensverwaltungsmandate des Asset Managements der Zürcher Kantonalbank». The firm was created as of 01.07.2015 as a result of the merger between Zürcher Kantonalbank and Swisscanto Group and includes all investment funds and exchange-traded funds previously managed by Swisscanto Group and Zürcher Kantonalbank. Until 28.02.2025 the GIPS firm name was «Swisscanto Fonds &amp; ZKB ETF», until 31.05.2022 the GIPS firm name was «Swisscanto Invest &amp; ZKB ETF».</p>
<p>&nbsp;</p>
<p>GIPS firm «Swisscanto Fonds &amp; ETF» has been independently verified for the period from 01.01.2011 to 30.06.2023 by PricewaterhouseCoopers AG.</p>
<h2>The following information can be found in the report</h2>
<ul>
<li>Quantitative key figures: all the data since the inception date of the strategy or, at maximum over the last 10 years, are shown.</li>
<li>The disclosure section of the GIPS report includes information regarding compliance with GIPS standards, the definition of the firm and information on the investment strategy as well as the methodology applied for calculating composite fund and benchmark returns and their risk measures. The composition of the benchmark used is also an important part of the disclosures.</li>
</ul>
