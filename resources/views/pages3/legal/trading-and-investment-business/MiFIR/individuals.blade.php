<div class="dt-container">






<div class=" instructions l-stack l-stack--goat">
    
    
        
        <div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Which information will the bank report?</h3>
<p>The bank will report information about the customer and any third party authorised by the same (particularly asset managers). This includes the first name, surname and date of birth as well as an identification number dependent on the nationality.<br>
</p>

</div>


    

</div>
<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h3>Who will the bank report this information to?</h3>
<p>Zürcher Kantonalbank will provide the customer information required by MiFIR to the relevant European trading venue. The trading venue then forwards the complete information to the supervisory authority responsible.</p>

</div>


    

</div>
