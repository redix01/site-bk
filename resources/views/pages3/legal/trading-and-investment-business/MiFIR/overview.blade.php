    <p>MiFIR is the abbreviation for Markets in Financial Instruments Regulation, the financial market regulation of the European Union (EU). According to the Markets in Financial Instruments Regulation (Article 26 MiFIR), trading venues in the European Economic Area must report any securities transactions (purchases and sales) carried out by direct participants from outside the European Economic Area to the responsible supervisory authorities. The trading venues as a consequence obligate their direct participants to provide the necessary customer information.</p>
<p>If Zürcher Kantonalbank is unable to pass on the necessary customer information, it may not be able to process the order for the customer or, as the case may be, only do so via another trading venue at less favourable conditions.<br>
</p>
<p>Requirements on reporting information of customers, whose securities orders are processed by Zürcher Kantonalbank as direct participant via a trading venue in the European Economic Area (see relevant trading venues and products):</p>
<ul>
<li>the customer has signed the Declaration of Consent</li>
<li>Zürcher Kantonalbank has been provided with the necessary customer information (see natural persons, legal entities)<br>
</li>
</ul>
<p>Last updated: January 2018</p>

