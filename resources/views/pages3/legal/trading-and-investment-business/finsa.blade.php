    <h3>What does the FinSA regulate and when does it affect you?</h3>
<p>The Swiss Financial Services Act (FinSA) entered into force on 1 January 2020. Its primary purpose is to strengthen investor protection when financial services are provided or financial instruments are offered. In particular, FinSA contains rules of conduct, including information and documentation requirements, as well as organisational measures.</p>
<p>FinSA applies to all financial services provided by financial service providers in Switzerland to clients who are resident in Switzerland or abroad.</p>
<p>The provisions of FinSA are set out in greater detail in the Financial Services Ordinance (FinSO).</p>
<p>A summary of some of the key information is provided below:</p>
<h3>Financial Services</h3>
<p>FinSA distinguishes between different types of financial services:</p>
<ul>
<li>Acquisition and disposal of financial instruments</li>
<li>Receipt and transmission of orders in relation to financial instruments</li>
<li>Administration of financial instruments (portfolio management)</li>
<li>&nbsp;Provision of personal recommendations on transactions with financial instruments (investment advice)</li>
<li>Granting of loans to finance transactions with financial instruments.</li>
</ul>
<p>Information on Zürcher Kantonalbank’s investment solutions can be found&nbsp;<a href="https://www.zkb.ch/de/private/anlagen.html">here</a>.</p>
<h3>Client segmentation</h3>
<p>For the purposes of providing financial services, FinSA requires financial service providers to classify their clients into different client segments: retail clients, professional clients or institutional clients. This classification is based on a person’s financial circumstances and level of knowledge, experience and financial expertise, the legally defined size of the company or the existence of a professional treasury.</p>
<p>Unless otherwise notified by Zürcher Kantonalbank, you are classified as a retail client and profit from the highest level of investor protection. If you meet the necessary requirements, you can request to change the client segment to which you are assigned. To do so, please contact your relationship manager.<br>
</p>
<p>If you are classified as a professional or institutional client, you will receive a corresponding classification letter from Zürcher Kantonalbank. As mentioned in the classification letter, please refer to the <a href="https://www.zkb.ch/media/zkb/dokumente/en/legal/client-segmentation.pdf">client information on client segmentation</a> for further details on these two client segments.</p>
<h3>Rules of conduct</h3>
<p>Depending on the assigned client segment, different rules of conduct must be observed in the provision of financial services, reflecting the relevant level of investor protection.</p>
<p>Zürcher Kantonalbank will provide you with various information before you enter into a contract or use a financial service. This information should make it easier for you to decide whether you wish to use a financial service. In the case of investment advisory or portfolio management services, the Bank will assess whether these are appropriate or suitable for you (in the case of execution-only transactions, such an assessment is not done). The Bank will document the provision of services and disclose this documentation to you on request.<br>
</p>
