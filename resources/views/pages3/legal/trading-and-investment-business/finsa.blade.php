<h3>Conflicts of interests</h3>
<p>Zürcher Kantonalbank always aims to organise its business activities in such a way that the interests of its clients, the bank and its employees are aligned as much as possible. However, as a universal bank, conflicts of interest cannot always be avoided. Zürcher Kantonalbank addresses such conflicts of interest transparently and professionally in compliance with the relevant legal requirements and based on the rules set out in the Code of Conduct of Zürcher Kantonalbank. It has internal policies and processes in place to manage conflicts of interest and takes measures to prevent conflicts of interest from having an adverse impact on its clients to the extent possible.</p>
<p>Further information on how Zürcher Kantonalbank deals with conflicts of interest, as well as information on the selected measures, can be found&nbsp;<a href="../conflict-of-interest.html">here</a>. You can also obtain the documents from your relationship manager on request.</p>

