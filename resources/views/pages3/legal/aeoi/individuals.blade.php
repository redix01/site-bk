<h3>Will Swiss nationals living abroad be reported?</h3>
<p>If you are a Swiss national living abroad and have your tax residence in a country that has concluded an AEOI agreement with Switzerland, you will be reported (see examples under "Will you be reported?").</p>
<h3>What information will the bank report?</h3>
<p>Customer details:</p>
<ul>
<li>Name</li>
<li>Address</li>
<li>Date of birth</li>
<li>TIN (Taxpayer Identification Number)</li>
</ul>
<p>Account number<br>
</p>
<ul>
<li>Financial information:</li>
<li>Account/custody account balance</li>
<li>Gross investment income, including interest and dividends</li>
<li>Gross capital gains</li>
</ul>
<h3>Who will the bank report your information to?</h3>
<p>To the Swiss Federal Tax Administration (SFTA). The SFTA will pass this information on to the tax authorities of the relevant country (please see "General – Which countries has Switzerland initiated AEOI agreements with?").</p>
