    <h3>When will the AEOI be implemented in Switzerland?</h3>
<p>Switzerland will implement the AEOI on 1 January 2017. From 2018, the Swiss Federal Tax Administration (SFTA) will report the relevant information to the respective tax authorities.</p>
<h3>Which countries has Switzerland initiated AEOI agreements with?</h3>
<p>To date, Switzerland has initiated AEOI agreements with the following countries:</p>
<ul>
<li>All 28 EU countries</li>
<li>Norway</li>
<li>Iceland</li>
<li>Canada</li>
<li>Australia</li>
<li>South Korea</li>
<li>Japan</li>
<li>Guernsey</li>
<li>Isle of Man</li>
<li>Jersey</li>
<li>These are expected to enter into force on 1 January 2017. Agreements will be made with additional countries over the next few months and years.&nbsp;</li>
</ul>
<h3>What does AEOI mean for the withholding tax agreement with the United Kingdom as well as with Austria?</h3>
<p>Austria and the United Kingdom have decided to participate in the AEOI. Customers resident in Austria and the United Kingdom will no longer have the option of anonymous withholding as from 1 January 2017.‎</p>
<h3>Which financial institutions are affected by AEOI?</h3>
<p>AEOI affects all financial institutions in Switzerland. They are obligated by law to implement AEOI from 1 January 2017.<br>
</p>

