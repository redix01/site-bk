    <p>In light of the worldwide goal of making tax evasion impossible, the member countries of the OECD and other major financial centres have decided to implement Automatic Exchange of Information (AEOI) for tax information. Switzerland is also participating in AEOI.</p>
<p>AEOI is a standard that regulates how the tax authorities of participating countries exchange data about the bank and custody accounts of taxpayers. It is based on the global standard for the international automatic exchange of information adopted by the OECD on 15 July 2014 (CRS – Common Reporting Standard).</p>
<p>The Federal AEOI Act, which came into effect on 1 January 2017, obligates all Swiss financial institutions, including Zürcher Kantonalbank, to report affected customers.</p>
