    <h2>Universal bank</h2>
<p>As a universal bank we are involved in all dimensions of banking business. We offer our clients comprehensive solutions and in doing so generate added value. The bank's strategy and structure is therefore based on client needs. We provide a specific performance promise for each client segment and offer comprehensive advice based on our clients' needs ‒ throughout their lives. Our organisation has been structured with this in mind.</p>

</div>


    

