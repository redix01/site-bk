<div class="text zkb-component zkb-component--text"><div class="t-richtext l-max-width l-max-width--apple l-stack l-stack--horse l-stack--cat@phone" data-component-is="text" data-component-id="text" data-analytics-component-name="Text">
    
    <h2>Corporate structure</h2>
<p>Zürcher Kantonalbank is an independent public law institution established and existing under the laws of Switzerland and the Canton of Zurich. The Board of Directors bears ultimate responsibility for the management of the bank and the supervision of the individuals entrusted with its operational management. As part of a structured process, it attends to the Group strategy on a twice-yearly basis, approves the consolidated risk inventory annually on the basis of a systematic analysis and deals with strategic risks. The&nbsp;Chairperson's Committee is responsible for the direct supervision of the Executive Board.</p>

