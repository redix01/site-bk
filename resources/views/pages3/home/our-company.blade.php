    <h2>The universal bank</h2>
<p>With total assets of around CHF 200 billion and more than 6,000 employees, we are the biggest cantonal bank in Switzerland and one of the biggest Swiss banks. We are the leader in universal banking business in the Greater Zurich Area. Our clients enjoy a wide range of products and services. &nbsp;</p>
<p>Since its establishment in 1870, Zürcher Kantonalbank has been an independent institution under public law (selbständige öffentlich-rechtliche Anstalt), established and existing under the laws of Switzerland and the canton of Zurich. Our public service mandate involves providing the population of Zurich with financial services, assisting the canton in fulfilling its economic, social and environmental obligations and adopting a responsible approach to the environment and society.</p>
<p>We operate the densest network of branches and ATMs in the canton of Zurich. We also operate at an international level in order to meet our clients' cross-border requirements.</p>
<h3>2024 key figures</h3>
<ul>
<li>Group profit before taxes: CHF 1,289 million</li>
<li>Total participation: CHF 562 million</li>
<li>Return on equity (RoE): 8.0 %</li>
<li>Total assets: CHF 203 billion</li>
<li>Net equity: CHF 14.9 billion</li>
</ul>

